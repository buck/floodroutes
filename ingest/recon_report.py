#!/usr/bin/env python3
"""Aggregate data/recon/*.json into docs/recon.md. Aggregates only, no case text."""
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECON = ROOT / "data" / "recon"
DOC = ROOT / "docs" / "recon.md"

FLOOD_TYPE_RE = re.compile(r"flood|drain|ditch|culvert|storm|water|sewer|inlet|pond|"
                           r"street hazard|high water|manhole|underpass|erosion|swale", re.I)
MIN_PREFIX = 20  # hide rare title prefixes, which can carry address fragments


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def label(f):
    m = re.search(r"(MTD|YTD-compressed-\d{4}|Harvey-clean|Harvey)", f)
    return m.group(1).replace("YTD-compressed-", "YTD ") if m else f


def main():
    files = [json.loads(p.read_text()) for p in sorted(RECON.glob("*.json"))]
    files.sort(key=lambda d: label(d["file"]))
    out = []
    w = out.append

    w("# Phase 0 recon: Houston 311 extracts\n")
    w("Generated by `ingest/recon_report.py` from `data/recon/*.json`. Aggregate counts only. "
      "The findings section is hand-written in `docs/recon_findings.md`; the numbered sections below are generated.\n")
    findings = ROOT / "docs" / "recon_findings.md"
    if findings.exists():
        w(findings.read_text())

    # ---- 1. schemas
    schemas = collections.OrderedDict()
    for d in files:
        schemas.setdefault(tuple(d["header"]), []).append(label(d["file"]))
    base = list(schemas)[0]
    w("## 1. Files and schemas\n")
    w("| File | Banner | Size | Columns | Schema |")
    w("|---|---|---:|---:|---|")
    names = {h: chr(65 + i) for i, h in enumerate(schemas)}
    for d in files:
        ban = " / ".join(b.strip("- ") for b in d.get("banner", []) if b.strip("- "))
        w(f"| {label(d['file'])} | {ban} | {d['bytes'] / 1e6:.0f} MB | {len(d['header'])} | {names[tuple(d['header'])]} |")
    w("")
    for h, fl in schemas.items():
        w(f"**Schema {names[h]}** ({', '.join(fl)}): {len(h)} columns")
        if h == base:
            w(f"\n`{' | '.join(h)}`\n")
        else:
            bu = {c.upper() for c in base}
            hu = {c.upper() for c in h}
            w(f"\n- Columns: `{' | '.join(h)}`")
            w(f"- Not in schema A: {', '.join(sorted(c for c in h if c.upper() not in bu)) or 'none'}")
            w(f"- Missing vs schema A: {', '.join(sorted(c for c in base if c.upper() not in hu)) or 'none'}\n")

    # ---- 2. rows / malformed
    w("## 2. Row counts and parse quality\n")
    w("Records are assembled from physical lines: a record starts on a line beginning with a case number; "
      "other lines are continuations of embedded line breaks in free text.\n")
    w("| File | Records | Multi-line | Malformed (too many / too few) | Non-UTF-8 lines | `none` markers (top) | Case-number shapes |")
    w("|---|---:|---:|---:|---:|---|---|")
    for d in files:
        s = d["stats"]
        nm = sorted(d["none_marker"].items(), key=lambda x: -x[1])[:3]
        shapes = ", ".join(f"`{k}` {v:,}" for k, v in list(d["case_number_shapes"].items())[:3])
        w(f"| {label(d['file'])} | {s.get('records', 0):,} | {s.get('records_multiline', 0):,} | "
          f"{s.get('malformed', 0):,} ({s.get('malformed_too_many', 0):,} / {s.get('malformed_too_few', 0):,}) | "
          f"{s.get('non_utf8_lines', 0):,} | {', '.join(f'{k} {v:,}' for k, v in nm) or '–'} | {shapes} |")
    w("")

    # ---- 3/4. per year coordinates. Year files only (MTD duplicates 2026 YTD; Harvey shown separately)
    def year_rows(sel):
        agg = collections.defaultdict(collections.Counter)
        for d in files:
            if sel(d):
                for y, c in d["per_year"].items():
                    agg[y].update(c)
        return agg

    yearly = year_rows(lambda d: "YTD" in d["file"])
    harvey = {label(d["file"]): d for d in files if "Harvey" in d["file"]}

    w("## 3–4. Coordinate completeness by created year\n")
    w("Year files (YTD) only; the MTD file overlaps the 2026 YTD. Bounding box: lon −95.95 to −94.90, lat 29.45 to 30.20.\n")
    w("| Year | Records | Lat/lon populated | In bbox | Zero | X/Y populated | X/Y in bbox (via EPSG:2278) | X/Y zero | Lat/lon vs X/Y > 100 m | TaxID populated |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")

    def yrow(name, c):
        n = c["records"]
        w(f"| {name} | {n:,} | {pct(c['latlon_populated'], n)} | {pct(c['latlon_in_bbox'], n)} | "
          f"{pct(c['latlon_zero'], n)} | {pct(c['xy_populated'], n)} | {pct(c['xy_in_bbox'], n)} | "
          f"{pct(c['xy_zero'], n)} | {c['latlon_xy_disagree_100m']:,} | {pct(c['taxid_populated'], n)} |")

    for y in sorted(yearly):
        yrow(y, yearly[y])
    for name, d in harvey.items():
        c = collections.Counter()
        for v in d["per_year"].values():
            c.update(v)
        yrow(f"{name} (all)", c)
    w("")
    w("**EPSG:2278 check** (distance between source lat/lon and transformed X/Y where both are in the bbox, sample ≤20k per file):\n")
    w("| File | n | p50 m | p90 m | p99 m | max m |")
    w("|---|---:|---:|---:|---:|---:|")
    for d in files:
        q = d["latlon_vs_xy_m"]
        if q["n"]:
            w(f"| {label(d['file'])} | {q['n']:,} | {q['p50']} | {q['p90']} | {q['p99']} | {q['max']:,} |")
    w("")

    # ---- 5. case types
    ct = collections.Counter()
    ct_year = collections.defaultdict(collections.Counter)
    dept, div, tp = collections.Counter(), collections.Counter(), collections.Counter()
    kw_type = collections.Counter()
    kw_hits = collections.Counter()
    tdd = collections.Counter()
    src = [d for d in files if "MTD" not in d["file"] and d["file"].find("Harvey.txt") < 0]
    for d in src:
        ct.update(d["case_types"])
        dept.update(d["departments"])
        div.update(d["divisions"])
        tp.update(d["title_prefix"])
        kw_type.update(d["kw_by_type"])
        kw_hits.update(d["kw_hits"])
        tdd.update(d["type_dept_div"])
        yr = label(d["file"])
        for t, n in d["case_types"].items():
            ct_year[t][yr] += n

    w("## 5. Case types, departments, divisions\n")
    w(f"Counts over all YTD files plus Harvey-clean (MTD and raw Harvey excluded as duplicates). "
      f"{len(ct):,} distinct case types.\n")
    w("### 5a. Case types that plausibly relate to flooding, drainage or standing water\n")
    w("Matched by name (`flood|drain|ditch|culvert|storm|water|sewer|inlet|pond|street hazard|high water|manhole|underpass|erosion|swale`), "
      "plus keyword-hit counts in free text for each type.\n")
    w("| Case type | Total | Strong kw hits | Weak kw hits | Years present | Dept / division (top) |")
    w("|---|---:|---:|---:|---|---|")
    for t, n in ct.most_common():
        if not FLOOD_TYPE_RE.search(t):
            continue
        yrs = sorted(ct_year[t])
        span = f"{yrs[0]}–{yrs[-1]}" if len(yrs) > 1 else yrs[0]
        top = max(((k, v) for k, v in tdd.items() if k.split("\t")[0] == t), key=lambda x: x[1])[0].split("\t")
        w(f"| {t} | {n:,} | {kw_type.get('strong\t' + t, 0):,} | {kw_type.get('weak\t' + t, 0):,} | {span} | {top[1]} / {top[2]} |")
    w("")
    w("### 5b. Other case types with many flood-keyword hits\n")
    w("| Case type | Strong kw hits | Weak kw hits | Total |")
    w("|---|---:|---:|---:|")
    other = collections.Counter()
    for k, v in kw_type.items():
        tier, t = k.split("\t", 1)
        if not FLOOD_TYPE_RE.search(t):
            other[t] += v
    for t, _ in other.most_common(25):
        w(f"| {t or '(blank)'} | {kw_type.get('strong\t' + t, 0):,} | {kw_type.get('weak\t' + t, 0):,} | {ct[t]:,} |")
    w("")
    w("### 5c. Keyword pattern hits (all text fields)\n")
    w("| Pattern | Records |")
    w("|---|---:|")
    for k, v in kw_hits.most_common():
        w(f"| `{k}` | {v:,} |")
    w("")
    w("### 5d. All case types\n")
    w("<details><summary>" + f"{len(ct):,} types" + "</summary>\n")
    w("| Case type | Count | Years |")
    w("|---|---:|---|")
    for t, n in ct.most_common():
        yrs = sorted(ct_year[t])
        w(f"| {t or '(blank)'} | {n:,} | {yrs[0]}–{yrs[-1]} |")
    w("\n</details>\n")
    w("### 5e. Departments\n")
    w("| Department | Count |\n|---|---:|")
    for k, v in dept.most_common():
        w(f"| {k or '(blank)'} | {v:,} |")
    w("")
    w("### 5f. Divisions (top 40)\n")
    w("| Division | Count |\n|---|---:|")
    for k, v in div.most_common(40):
        w(f"| {k or '(blank)'} | {v:,} |")
    w("")
    w(f"### 5g. Title prefixes (top 40, count ≥ {MIN_PREFIX})\n")
    w("| Title prefix | Count |\n|---|---:|")
    for k, v in [(k, v) for k, v in tp.most_common() if v >= MIN_PREFIX][:40]:
        w(f"| {k or '(blank)'} | {v:,} |")
    w("")

    # ---- storm-day preview
    daily = collections.Counter()
    daily_sewer = collections.Counter()
    for d in src:
        for k, v in d["flood_type_daily"].items():
            t, day = k.split("\t")
            if re.search(r"drain|flood", t, re.I) and not re.search(r"billing|floodplain|violation", t, re.I):
                daily[day] += v
            if t == "Sewer Wastewater":
                daily_sewer[day] += v
    w("## Storm-day preview\n")
    w("Daily counts of drainage/flooding case types (Drainage, Flooding, Poor Drainage and similar; billing, floodplain and violation types excluded). "
      "Phase 2 will set the threshold properly; this is the top 30 for a first check against known events.\n")
    vals = sorted(daily.values())
    if vals:
        p99 = vals[int(.99 * (len(vals) - 1))]
        w(f"{len(vals):,} days with any such request; median {vals[len(vals) // 2]}/day, p99 {p99}/day.\n")
    w("| Day | Drainage/flooding requests | Sewer Wastewater same day |")
    w("|---|---:|---:|")
    for day, n in daily.most_common(30):
        w(f"| {day} | {n:,} | {daily_sewer.get(day, 0):,} |")
    w("")

    # ---- 6. geocoding estimate
    w("## 6. Records needing geocoding\n")
    w("A record *needs geocoding* when neither source lat/lon nor transformed X/Y falls in the bbox.\n")
    w("| Year | Records | Needs geocode | Of which intersection-style address |")
    w("|---|---:|---:|---:|")
    tot = collections.Counter()
    for y in sorted(yearly):
        c = yearly[y]
        tot.update(c)
        w(f"| {y} | {c['records']:,} | {c['needs_geocode']:,} ({pct(c['needs_geocode'], c['records'])}) | {c['needs_geocode_intersection']:,} |")
    w(f"| **All YTD** | {tot['records']:,} | {tot['needs_geocode']:,} ({pct(tot['needs_geocode'], tot['records'])}) | {tot['needs_geocode_intersection']:,} |")
    for name, d in harvey.items():
        c = collections.Counter()
        for v in d["per_year"].values():
            c.update(v)
        w(f"| {name} | {c['records']:,} | {c['needs_geocode']:,} ({pct(c['needs_geocode'], c['records'])}) | {c['needs_geocode_intersection']:,} |")
    w("")

    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(out))
    print(f"wrote {DOC} ({len(out)} lines)")


if __name__ == "__main__":
    main()
