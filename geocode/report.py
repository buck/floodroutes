#!/usr/bin/env python3
"""Write docs/geocode_report.md and docs/geocode_flood_points.png (aggregates and points only)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ingest"))
from db import connect  # noqa: E402

DOC = ROOT / "docs" / "geocode_report.md"
PNG = ROOT / "docs" / "geocode_flood_points.png"


def main():
    L = []
    w = L.append
    with connect() as conn:
        q = conn.execute
        w("# Phase 3: geocoding report\n")
        w("Generated by `geocode/report.py`. Precision is `source_point` for city-supplied coordinates, "
          "`address` for Census batch matches, `failed` otherwise.\n")
        w("## All cases by method and precision\n")
        w("| Method | Precision | Cases |\n|---|---|---:|")
        for m, p, n in q("""SELECT coalesce(geocode_method,'(not yet)'), coalesce(geocode_precision,'(not yet)'), count(*)
                            FROM core.service_request GROUP BY 1,2 ORDER BY 3 DESC"""):
            w(f"| {m} | {p} | {n:,} |")
        w("")
        n_dis = q("SELECT count(*) FROM core.service_request WHERE geocode_note LIKE 'latlon_xy_disagree%'").fetchone()[0]
        w(f"Lat/lon and X/Y disagreed by > 100 m (X/Y used, logged in `geocode_note`): **{n_dis:,}** cases.\n")
        ph = q("SELECT lon, lat, records, case_types FROM core.geocode_placeholder ORDER BY records DESC").fetchall()
        w("Placeholder points treated as missing (≥ 2,000 records across ≥ 40 case types): "
          + "; ".join(f"({lo}, {la}) — {n:,} records, {t} types" for lo, la, n, t in ph) + ".\n")

        w("## Flood-signal cases\n")
        w("| Tier | Cases | source_point | address | failed | Located |\n|---|---:|---:|---:|---:|---:|")
        tot = [0, 0]
        for tier, n, sp, ad, fl in q("""
            SELECT f.tier, count(*), count(*) FILTER (WHERE geocode_precision='source_point'),
                   count(*) FILTER (WHERE geocode_precision='address'), count(*) FILTER (WHERE geocode_precision='failed')
            FROM core.flood_signal f JOIN core.service_request r USING (case_number)
            GROUP BY 1 ORDER BY array_position(ARRAY['strong','moderate','weak'], f.tier)"""):
            w(f"| {tier} | {n:,} | {sp:,} | {ad:,} | {fl:,} | {100 * (sp + ad) / n:.1f}% |")
            tot[0] += n
            tot[1] += sp + ad
        w(f"| **all** | {tot[0]:,} | | | | **{100 * tot[1] / tot[0]:.1f}%** |\n")
        w("Acceptance target: ≥ 95% of flood-signal records at address precision or better "
          f"({'met' if tot[1] / tot[0] >= 0.95 else 'NOT met'}).\n")
        w("Failures are records with neither a usable source point nor an address: almost all are "
          "2011 records the city migrated without location, or older records with a blank address.\n")

        w("## Failure rate by created year (all cases)\n")
        w("| Year | Cases | Failed | Rate |\n|---|---:|---:|---:|")
        for y, n, fl in q("""SELECT extract(year FROM created_local)::int, count(*),
                                    count(*) FILTER (WHERE geocode_precision='failed')
                             FROM core.service_request GROUP BY 1 ORDER BY 1"""):
            w(f"| {y} | {n:,} | {fl:,} | {100 * fl / n:.1f}% |")
        w("")
        w("## Map preview\n")
        w(f"![Flood-signal points by tier]({PNG.name})\n")
        pts = q("""SELECT f.tier, ST_X(r.geom), ST_Y(r.geom) FROM core.flood_signal f
                   JOIN core.service_request r USING (case_number) WHERE r.geom IS NOT NULL""").fetchall()

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(10, 9), dpi=120)
    for tier, color, size in (("weak", "#9ca3af", 0.3), ("moderate", "#3b82f6", 0.3), ("strong", "#dc2626", 0.6)):
        xs = [p[1] for p in pts if p[0] == tier]
        ys = [p[2] for p in pts if p[0] == tier]
        ax.scatter(xs, ys, s=size, c=color, alpha=0.5, linewidths=0, label=f"{tier} ({len(xs):,})")
    ax.set_xlim(-95.85, -95.0)
    ax.set_ylim(29.5, 30.12)
    ax.set_aspect(1 / 0.867)  # cos(29.8°)
    ax.set_title("Houston 311 flood-signal cases, 2011–2026")
    ax.legend(markerscale=12, loc="lower left", frameon=False)
    ax.set_xlabel("longitude")
    ax.set_ylabel("latitude")
    fig.tight_layout()
    fig.savefig(PNG)
    DOC.write_text("\n".join(L))
    print(f"wrote {DOC} and {PNG}")


if __name__ == "__main__":
    main()
